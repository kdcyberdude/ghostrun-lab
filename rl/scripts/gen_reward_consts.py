"""Generate rl/csrc/reward10_consts.h from the Python reward10 modules (the source of truth).

Every number the GPU reward needs (weights, units, stall limits, Kage route segments) is read from
scripts/reward10 here and written as exact hex-float literals, so the CUDA port cannot drift from Python.

usage: python rl/scripts/gen_reward_consts.py           rewrite the header
       python rl/scripts/gen_reward_consts.py --check   exit 1 if the header is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts' / 'reward10'))
import contract  # noqa: E402
import reward as R  # noqa: E402

GAMES = ['smb', 'pacman', 'excitebike', 'contra', 'castlevania', 'gradius', 'zelda', 'tetris', 'tecmobowl', 'kage',
         'finalmission', 'punchout']
OUT = ROOT / 'rl' / 'csrc' / 'reward10_consts.h'


def hx(v: float) -> str:
    return float(v).hex()


def build() -> str:
    mods = {g: contract.load(g) for g in GAMES}
    for g, m in mods.items():
        assert m.DEATH_FROM in ('dying', 'lives'), g
    L = ['// GENERATED by rl/scripts/gen_reward_consts.py from scripts/reward10. Do not edit.', '#pragma once',
         '#include <cstdint>', 'namespace rl10 {', '']
    L.append(f'constexpr int kNumGames = {len(GAMES)};')
    for i, g in enumerate(GAMES):
        L.append(f'constexpr int kGame_{g} = {i};')
    for k in ('W_PROGRESS', 'W_LEVEL', 'W_DEATH', 'W_STALL', 'W_DAMAGE', 'W_SCORE', 'SCORE_CAP', 'SCORE_LEVEL_BUDGET', 'W_WIN',
              'W_ROLLBACK', 'ROLLBACK_DROP', 'NES_FPS'):
        L.append(f'constexpr double k{k} = {hx(getattr(R, k))};  // {getattr(R, k)!r}')
    rows = []
    for g in GAMES:
        m = mods[g]
        stall = getattr(m, 'STALL_SECONDS', R.STALL_SECONDS)
        stall_frames = -1.0 if stall is None else stall * R.NES_FPS
        ss = getattr(m, 'START_SELECT', {})
        rows.append(f'    {{{hx(m.PROGRESS_UNIT)}, {hx(m.SCORE_UNIT)}, {hx(stall_frames)}, {hx(R.idle_per_frame(m))}, '
                    f'{1 if m.DEATH_FROM == "lives" else 0}, {1 if "START" in ss else 0}, {1 if "SELECT" in ss else 0}}},'
                    f'  // {g}')
    L += ['', 'struct GameConsts { double progress_unit, score_unit, stall_frames, idle_per_frame; int death_from_lives, start_ok, '
          'select_ok; };', 'constexpr GameConsts kGameConsts[kNumGames] = {', *rows, '};', '']
    # Kage routes: segments (x0, y0, x1, y1, L, acc) and total, exactly as kage.SEGMENTS computes them.
    k = mods['kage']
    stages = sorted(k.SEGMENTS)
    seg_rows, index = [], []
    for s in stages:
        segs, total = k.SEGMENTS[s]
        index.append(f'    {{{s}, {len(seg_rows)}, {len(segs)}, {hx(total)}}},')
        for (x0, y0, x1, y1, Ln, acc) in segs:
            seg_rows.append(f'    {{{hx(x0)}, {hx(y0)}, {hx(x1)}, {hx(y1)}, {hx(Ln)}, {hx(acc)}}},')
    L += ['struct KageSeg { double x0, y0, x1, y1, len, acc; };',
          'struct KageRoute { int stage, first, count; double total; };',
          f'constexpr int kKageNumRoutes = {len(stages)};',
          f'constexpr KageSeg kKageSegs[{len(seg_rows)}] = {{', *seg_rows, '};',
          f'constexpr KageRoute kKageRoutes[{len(stages)}] = {{', *index, '};',
          f'constexpr double kKageLookahead = {hx(k.LOOKAHEAD)};',
          f'constexpr double kKageMaxOff = {hx(k.MAX_OFF)};']
    bosses = ', '.join(f'{{{s}, {a}, {b}, {c}}}' for s, (a, b, c) in sorted(k.BOSSES.items()))
    L += ['struct KageBoss { int stage, kind, sel, max_hp; };',
          f'constexpr KageBoss kKageBosses[{len(k.BOSSES)}] = {{{bosses}}};', '']
    # Small per-game constants used by the readers (checked against the modules, not retyped).
    c, cv, z, t, f, p, e = (mods[n] for n in ('contra', 'castlevania', 'zelda', 'tecmobowl', 'finalmission',
                                               'punchout', 'excitebike'))
    assert c.BOSS_CORE == {0: (0x11, 32)} and c.ROOM_CORE_TYPE == 0x14
    assert cv.BOSS_STAGES == (3, 6, 9, 12, 15, 18) and cv.CELL_W == 32 and cv.FLOOR_STEP == 40
    assert z.PLAY_MODES == (5, 0xB) and z.DEATH_MODE == 0x11
    assert t.PLAY_SCREENS == ((8, 0), (9, 9), (12, 12)) and t.LAST_WEEK == 10
    assert f.HUD_PIPS == 4 and f.BOSS_MIN_HP == 20
    assert p.FULL_HEALTH == 96 and p.LAST_FIGHT == 13 and p.LOSS_STATES == (249, 251, 253)
    assert p.WIN_STATES == (250, 252, 254) and e.OVERHEAT == 32 and mods['pacman'].DOTS_PER_MAZE == 192
    L += [f'constexpr double kContraRoomUnits = {hx(c.ROOM_UNITS)};',
          f'constexpr double kContraBossUnits = {hx(c.BOSS_UNITS)};',
          f'constexpr double kCastleBossUnits = {hx(cv.BOSS_UNITS)};',
          f'constexpr double kTecmoPxPerYard = {hx(t.PX_PER_YARD)};',
          f'constexpr int kTecmoGoalX = {t.GOAL_X};',
          f'constexpr double kFinalBossUnits = {hx(f.BOSS_UNITS)};',
          f'constexpr double kPunchProgressUnit = {hx(p.PROGRESS_UNIT)};',
          'constexpr int kZeldaItemAddr[] = {' + ', '.join(f'0x{a:X}' for a in z.ITEMS) + '};',
          'constexpr int kZeldaItemCap[] = {' + ', '.join(str(v) for v in z.ITEMS.values()) + '};',
          f'constexpr int kZeldaNumItems = {len(z.ITEMS)};',
          '', '}  // namespace rl10', '']
    return '\n'.join(device_copies(L))


def device_copies(L):
    """Every constexpr array also gets a __constant__ device copy d_<name>; code reads it through RL10_ARR(name)."""
    out, i = [], 0
    while i < len(L):
        line = L[i]
        if line.startswith('constexpr ') and '[' in line.split('=')[0]:
            j = i
            while not L[j].rstrip().endswith('};'):
                j += 1
            block = L[i:j + 1]
            out += block
            name = line.split('=')[0].split()[-1].split('[')[0]
            dev = ['__constant__ ' + block[0][len('constexpr '):].replace(name + '[', 'd_' + name + '[', 1)] + block[1:]
            out += ['#ifdef __CUDACC__', *dev, '#endif']
            i = j + 1
        else:
            out.append(line)
            i += 1
    k = out.index('namespace rl10 {')
    out[k:k] = ['#ifdef __CUDA_ARCH__', '#define RL10_ARR(x) d_##x', '#else', '#define RL10_ARR(x) x', '#endif']
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT} is stale: run python rl/scripts/gen_reward_consts.py')
            sys.exit(1)
        print('reward10_consts.h is current')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
